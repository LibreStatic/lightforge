enum class SemanticModelCompatibility { Recommended, Supported, TechnicallyUnsupported }

data class SemanticModelDescriptor(
    val id: String,
    val displayName: String,
    val version: String,
    val packageUrl: String,
    val packageBytes: Long,
    val packageSha256: String,
    val signatureBase64: String,
    val minimumRamMb: Int,
    val recommendedRamMb: Int,
    val embeddingDimensions: Int = 512,
) {
    init {
        require(id.matches(Regex("[a-z0-9-]+")))
        require(packageUrl.startsWith("https://github.com/LibreStatic/lightforge-models/releases/download/"))
        require(packageBytes > 0)
        require(packageSha256.matches(Regex("[a-f0-9]{64}")))
        require(signatureBase64.isNotBlank())
        require(embeddingDimensions == CompactSemanticEmbedding.Dimensions)
    }
}

