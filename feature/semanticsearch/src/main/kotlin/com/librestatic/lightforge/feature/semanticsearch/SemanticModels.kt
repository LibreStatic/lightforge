data class SemanticHardwareProfile(
    val totalRamMb: Int,
    val supportedAbis: List<String>,
)

object SemanticModelSelector {
    fun profile(context: Context): SemanticHardwareProfile {
        val memory = ActivityManager.MemoryInfo()
        context.getSystemService(ActivityManager::class.java).getMemoryInfo(memory)
        return SemanticHardwareProfile(
            totalRamMb = (memory.totalMem / (1024L * 1024L)).toInt(),
            supportedAbis = Build.SUPPORTED_ABIS.toList(),
        )
    }

    fun compatibility(model: SemanticModelDescriptor, profile: SemanticHardwareProfile): SemanticModelCompatibility {
        if (profile.supportedAbis.none { it == "arm64-v8a" || it == "x86_64" } ||
            profile.totalRamMb < model.minimumRamMb
        ) return SemanticModelCompatibility.TechnicallyUnsupported
        return if (profile.totalRamMb >= model.recommendedRamMb) {
            SemanticModelCompatibility.Recommended
        } else {
            SemanticModelCompatibility.Supported
        }
    }

    fun recommended(models: List<SemanticModelDescriptor>, profile: SemanticHardwareProfile): SemanticModelDescriptor? =
        models.filter { compatibility(it, profile) != SemanticModelCompatibility.TechnicallyUnsupported }
            .maxByOrNull { model ->
                val preferred = compatibility(model, profile) == SemanticModelCompatibility.Recommended
                (if (preferred) 1_000_000 else 0) + model.recommendedRamMb
            }
}

data class InstalledSemanticModel(
    val descriptor: SemanticModelDescriptor,
    val directory: File,
) {
    val imageModel: File get() = directory.resolve("image.tflite")
    val textModel: File get() = directory.resolve("text.tflite")
    val vocabulary: File get() = directory.resolve("vocab.json")
    val merges: File get() = directory.resolve("merges.txt")
}
