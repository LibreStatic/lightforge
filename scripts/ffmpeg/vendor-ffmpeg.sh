#!/usr/bin/env bash
# Vendors the minimal LGPL subset of FFmpeg needed to decode Sorenson Spark (flv), VP6F and VP6A
# into core/legacy-video/third_party/ffmpeg. It cross-builds libavcodec per ABI with the NDK,
# reads the compiler dependency files (.d) to learn which sources/headers are really used, and
# copies only those. Nothing is downloaded at Gradle build time; rerun this script to regenerate.
#
#   scripts/ffmpeg/vendor-ffmpeg.sh            (needs the Android NDK, curl, tar, xz, make, python3)
#   Env: WORK (scratch, default ~/.cache/claude-tmp/lightforge/ffmpeg), NDK, JOBS (default 6, max 6)
set -euo pipefail

VERSION=7.1.2
SHA256=089bc60fb59d6aecc5d994ff530fd0dcb3ee39aa55867849a2bbc4e555f9c304
URL="https://ffmpeg.org/releases/ffmpeg-${VERSION}.tar.xz"
API=30
ABIS="arm64-v8a armeabi-v7a x86_64"

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
DEST="$REPO/core/legacy-video/third_party/ffmpeg"
WORK="${WORK:-$HOME/.cache/claude-tmp/lightforge/ffmpeg}"
NDK="${NDK:-${ANDROID_HOME:-$HOME/Android/Sdk}/ndk/27.1.12297006}"
JOBS="${JOBS:-6}"; [ "$JOBS" -gt 6 ] && JOBS=6
TOOLS="$NDK/toolchains/llvm/prebuilt/linux-x86_64"
[ -d "$TOOLS" ] || { echo "NDK not found at $NDK" >&2; exit 1; }

mkdir -p "$WORK/dl"
TARBALL="$WORK/dl/ffmpeg-${VERSION}.tar.xz"
[ -f "$TARBALL" ] || curl -fL -o "$TARBALL" "$URL"
echo "$SHA256  $TARBALL" | sha256sum -c -

rm -rf "$WORK/vendor"; mkdir -p "$WORK/vendor/extract"
tar -C "$WORK/vendor/extract" -xf "$TARBALL"
SRC="$WORK/vendor/extract/ffmpeg-${VERSION}"

COMMON_FLAGS=(
  --disable-everything --disable-asm --disable-programs --disable-doc --disable-network
  --disable-avdevice --disable-avformat --disable-avfilter --disable-swresample
  --disable-swscale --disable-postproc --disable-autodetect --disable-jni
  --disable-mediacodec --disable-hwaccels --disable-debug --disable-stripping
  --enable-decoder=flv,vp6f,vp6a --enable-pic --enable-small
  --enable-cross-compile --target-os=android
)

for abi in $ABIS; do
  case $abi in
    arm64-v8a)   arch=aarch64; cpu=armv8-a; triple=aarch64-linux-android ;;
    armeabi-v7a) arch=arm; cpu=armv7-a; triple=armv7a-linux-androideabi ;;
    x86_64)      arch=x86_64; cpu=x86-64; triple=x86_64-linux-android ;;
  esac
  B="$WORK/vendor/build-$abi"; mkdir -p "$B"
  ( cd "$B" && "$SRC/configure" "${COMMON_FLAGS[@]}" --arch=$arch --cpu=$cpu \
      --cc="$TOOLS/bin/${triple}${API}-clang" --ar="$TOOLS/bin/llvm-ar" \
      --ranlib="$TOOLS/bin/llvm-ranlib" --nm="$TOOLS/bin/llvm-nm" \
      --strip="$TOOLS/bin/llvm-strip" --sysroot="$TOOLS/sysroot" \
      --extra-cflags="-MMD" > configure.log 2>&1 \
    && make -j"$JOBS" libavcodec/libavcodec.a libavutil/libavutil.a > make.log 2>&1 ) \
    || { echo "build failed for $abi, see $B/*.log" >&2; exit 1; }
done

rm -rf "$DEST"; mkdir -p "$DEST"
python3 -I - "$SRC" "$WORK/vendor" "$DEST" $ABIS <<'PY'
import os, re, shutil, sys
src, work, dest, *abis = sys.argv[1:]
src = os.path.realpath(src)
shared = {}          # relative path -> True (copied from the source tree)
for abi in abis:
    b = os.path.realpath(f"{work}/build-{abi}")
    srcs, gen = [], set()
    for root, _, files in os.walk(b):
        for f in files:
            if not f.endswith(".d"): continue
            txt = open(os.path.join(root, f)).read().replace("\\\n", " ")
            toks = txt.split()
            obj = toks[0].rstrip(":")
            deps = [t for t in toks[1:] if t != ":"]
            for t in deps:
                p = os.path.realpath(os.path.join(b, t)) if not os.path.isabs(t) else os.path.realpath(t)
                if p.startswith(src + "/"):
                    shared[os.path.relpath(p, src)] = True
                elif p.startswith(b + "/"):
                    gen.add(os.path.relpath(p, b))
            # first dependency is the translation unit
            first = os.path.realpath(os.path.join(b, deps[0]))
            if first.startswith(src + "/"): srcs.append(os.path.relpath(first, src))
            elif first.startswith(b + "/"): srcs.append("@" + os.path.relpath(first, b))
    for g in gen:
        d = os.path.join(dest, "config", abi, g)
        os.makedirs(os.path.dirname(d), exist_ok=True)
        shutil.copy(os.path.join(b, g), d)
    srcs = sorted(set(srcs))
    with open(os.path.join(dest, "config", abi, "sources.cmake"), "w") as o:
        o.write("# Generated by scripts/ffmpeg/vendor-ffmpeg.sh. Do not edit.\nset(FFMPEG_SOURCES\n")
        for s in srcs:
            if s.startswith("@"): o.write(f"    ${{FFMPEG_CONFIG_DIR}}/{s[1:]}\n")
            else: o.write(f"    ${{FFMPEG_ROOT}}/{s}\n")
        o.write(")\n")
for rel in sorted(shared):
    d = os.path.join(dest, rel)
    os.makedirs(os.path.dirname(d), exist_ok=True)
    shutil.copy(os.path.join(src, rel), d)
shutil.copy(os.path.join(src, "COPYING.LGPLv2.1"), dest)
PY

FLAGS="$(printf '%s ' "${COMMON_FLAGS[@]}")"
cat > "$DEST/VENDORED.txt" <<TXT
FFmpeg ${VERSION} (LGPL 2.1+ only: no --enable-gpl, no --enable-nonfree)
Source:  ${URL}
SHA-256: ${SHA256}

Only libavcodec/libavutil sources and headers that the flv, vp6f and vp6a decoders
actually compile are kept (FFmpeg's directory layout). Per-ABI generated files
(config.h, config_components.h, codec_list.c, ... and sources.cmake) are in config/<abi>/.

Common configure flags: ${FLAGS}
Per ABI: --arch/--cpu/--cc/--ar/--ranlib/--nm/--strip/--sysroot of NDK 27.1.12297006, API ${API}, --extra-cflags=-MMD.

Regenerate with scripts/ffmpeg/vendor-ffmpeg.sh
TXT
du -sh "$DEST"
